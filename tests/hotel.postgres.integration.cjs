const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const load=require('./loadModule.cjs');
if(process.env.MBF_ISOLATED_TEST!=='1'||!['postgresql://ci:ci@127.0.0.1:55439/ci','postgres://ci:ci@localhost:5432/ci','postgresql://ci:ci@localhost:5432/ci'].includes(process.env.DATABASE_URL))throw Error('Disposable localhost database required');
const {PrismaClient}=require('@prisma/client');const base=new PrismaClient();
const db=load('src/lib/databaseTransaction.ts',{'node:async_hooks':require('node:async_hooks'),'@/lib/databaseClientContext':load('src/lib/databaseClientContext.ts')});
const prisma=db.transactionAwareClient(base),lock=load('src/lib/withRecordLock.ts',{'@/lib/prisma':{prisma},'@/lib/databaseTransaction':db});
const rules=load('src/lib/hotelRules.ts'),partnerId='hotel-test-'+crypto.randomUUID();
let signedIn=true,enabled=true;
const hotel=load('src/lib/hotel.ts',{'node:crypto':crypto,'@/lib/prisma':{prisma},'@/lib/withRecordLock':lock,'@/lib/hotelRules':rules,
 '@/lib/requirePartnerSession':{requireSessionPartnerId:async()=>{if(!signedIn)throw Error('owner required');}},
 '@/lib/tenant':{assertModuleAccess:async()=>{if(!enabled)throw Error('module disabled');},assertPartnerCanWrite:async()=>{}},
});
const today=rules.hotelToday(),day=n=>new Date(Date.parse(today)+n*86400000).toISOString().slice(0,10);
const roomInput={name:'101',roomType:'Standard',capacity:2,rateRupees:1000,status:'Ready'};
test('Hotel validates dates, scopes records, serializes reservations and retains rate snapshots',async()=>{
 signedIn=false;await assert.rejects(hotel.listHotelRooms(partnerId),/owner/);signedIn=true;
 enabled=false;await assert.rejects(hotel.saveHotelRoom(partnerId,null,roomInput),/disabled/);enabled=true;
 assert.throws(()=>rules.hotelNights('2030-02-30','2030-03-03'),/valid/);
 assert.throws(()=>rules.hotelNights(today,today),/365/);
 const roomId=await hotel.saveHotelRoom(partnerId,null,roomInput);
 await assert.rejects(hotel.saveHotelRoom(partnerId,null,{...roomInput,name:'101 '}),/already exists/);
 const input={roomId,guest:'Test guest',guests:2,arrival:today,departure:day(1)};
 await assert.rejects(hotel.reserveHotelStay(partnerId+'-foreign',input),/Room not found/);
 await assert.rejects(hotel.reserveHotelStay(partnerId,{...input,guests:3}),/capacity/);
 const results=await Promise.allSettled([hotel.reserveHotelStay(partnerId,input),hotel.reserveHotelStay(partnerId,input)]);
 assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
 const id=results.find(r=>r.status==='fulfilled').value;
 await assert.rejects(hotel.getHotelStay(partnerId+'-foreign',id),/not found/);
 await hotel.saveHotelRoom(partnerId,roomId,{...roomInput,rateRupees:1200});
 assert.equal((await hotel.getHotelStay(partnerId,id)).ratePaise,100000);
 const next=await hotel.reserveHotelStay(partnerId,{...input,arrival:day(1),departure:day(2)});
 await assert.rejects(hotel.rescheduleHotelStay(partnerId,id,today,day(2)),/already reserved/);
 await assert.rejects(hotel.saveHotelRoom(partnerId,roomId,{...roomInput,status:'Out of service'}),/Existing reservations/);
 await assert.rejects(hotel.saveHotelRoom(partnerId,roomId,{...roomInput,capacity:1}),/Existing reservations/);
 await hotel.saveHotelRoom(partnerId,roomId,{...roomInput,status:'Dirty'});
 await assert.rejects(hotel.transitionHotelStay(partnerId,id,'check-in'),/Ready/);
 await hotel.saveHotelRoom(partnerId,roomId,roomInput);
 await hotel.transitionHotelStay(partnerId,id,'check-in');
 await assert.rejects(hotel.saveHotelRoom(partnerId,roomId,roomInput),/occupied/);
 await assert.rejects(hotel.transitionHotelStay(partnerId,id,'check-out'),/Settle/);
 await hotel.postHotelFolio(partnerId,id,{kind:'Charge',reference:'extra1',label:'Breakfast',amount:100});
 const payment={kind:'Payment',paymentMethod:'Cash',reference:'receipt1',label:'Cash received',amount:1100};
 await Promise.all([hotel.postHotelFolio(partnerId,id,payment),hotel.postHotelFolio(partnerId,id,payment)]);
 const stay=await hotel.getHotelStay(partnerId,id);assert.equal(stay.entries.length,2);assert.equal(rules.hotelBalance(stay).balance,0);
 await assert.rejects(hotel.postHotelFolio(partnerId,id,{...payment,amount:1}),/different transaction/);
 await assert.rejects(hotel.postHotelFolio(partnerId,id,{...payment,reference:'overpay',amount:1}),/outstanding/);
 await hotel.transitionHotelStay(partnerId,id,'check-out');
 assert.equal((await hotel.listHotelRooms(partnerId))[0].status,'Dirty');
 await assert.rejects(hotel.postHotelFolio(partnerId,id,{...payment,reference:'closed'}),/closed/);
 await assert.rejects(hotel.transitionHotelStay(partnerId,next,'check-in'),/reserved stay dates/);
 await hotel.postHotelFolio(partnerId,next,{kind:'Payment',paymentMethod:'Cash',reference:'deposit',label:'Deposit received',amount:200});
 await assert.rejects(hotel.transitionHotelStay(partnerId,next,'cancel'),/refund/);
 await assert.rejects(hotel.postHotelFolio(partnerId,next,{kind:'Refund',paymentMethod:'Cash',reference:'excess',label:'Refund',amount:201}),/exceed/);
 await hotel.postHotelFolio(partnerId,next,{kind:'Refund',paymentMethod:'Cash',reference:'refund',label:'Deposit refunded',amount:200});
 await hotel.transitionHotelStay(partnerId,next,'cancel');assert.equal(rules.hotelBalance(await hotel.getHotelStay(partnerId,next)).balance,0);
 await hotel.saveHotelRoom(partnerId,roomId,{...roomInput,status:'Out of service'});
 await assert.rejects(hotel.reserveHotelStay(partnerId,{...input,arrival:day(1),departure:day(2)}),/out of service/);
 assert.equal((await hotel.listHotelStays(partnerId)).stays.length,2);
});
test.after(async()=>{await base.businessRecord.deleteMany({where:{partnerId}});await base.$disconnect();});
