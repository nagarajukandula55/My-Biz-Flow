const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const load = require('./loadModule.cjs');
if (process.env.MBF_ISOLATED_TEST !== '1' || process.env.DATABASE_URL !== 'postgresql://ci:ci@127.0.0.1:55439/ci') throw Error('Disposable local database required');
const { PrismaClient } = require('@prisma/client');
const base = new PrismaClient();
const db = load('src/lib/databaseTransaction.ts', { 'node:async_hooks': require('node:async_hooks'), '@/lib/databaseClientContext': load('src/lib/databaseClientContext.ts') });
const prisma = db.transactionAwareClient(base);
const lock = load('src/lib/withRecordLock.ts', { '@/lib/prisma': { prisma }, '@/lib/databaseTransaction': db });
let owner = true;
const common = { '@/lib/prisma': { prisma }, '@/lib/withRecordLock': lock, '@/lib/tenant': { assertModuleAccess: async()=>{}, assertPartnerCanWrite:async()=>{} }, '@/lib/requirePartnerSession': { requireSessionPartnerId: async()=>{if(!owner)throw Error('Owner required');} } };
const hrms = load('src/lib/hrms.ts', { ...common, 'node:crypto':crypto, '@/lib/databaseTransaction':db, '@/lib/format':load('src/lib/format.ts'), '@/lib/telegram':{sendPartnerTelegramAlert:async()=>{}}, '@/lib/partnerData':{getPartner:async()=>null}, '@/lib/telegramTemplates':{}, '@/lib/email/moduleEmails':{} });
const payroll = load('src/lib/hrmsAttendancePayroll.ts', { ...common, 'node:crypto':crypto, '@/lib/hrms':hrms, '@/lib/hrmsPayrollCalculation':load('src/lib/hrmsPayrollCalculation.ts') });
const partnerId = 'payroll-qa-' + crypto.randomUUID();
test('attendance payroll is owner scoped, atomic, audited and protects finalized periods', async()=>{
  const employee = await prisma.employee.create({data:{partnerId,name:'Synthetic payroll employee'}});
  const shift = await prisma.attendanceCheckIn.create({data:{employeeId:employee.id,checkInAt:new Date('2020-01-02T03:30:00Z'),checkOutAt:new Date('2020-01-02T11:30:00Z'),status:'HalfDay'}});
  const values = { employeeId:employee.id, month:1,year:2020,basicPay:23000,allowances:100,deductions:0,workingWeekdays:['Monday','Tuesday','Wednesday','Thursday','Friday'],paidLeaveDays:1,reviewReason:'Approved one paid leave day' };
  await assert.rejects(payroll.createAttendancePayroll(partnerId+'-other', values),/not found/);
  owner=false; try { await assert.rejects(payroll.createAttendancePayroll(partnerId, values),/Owner/); } finally {owner=true;}
  const slip = await payroll.createAttendancePayroll(partnerId, values);
  assert.equal(slip.status,'Draft'); assert.equal(slip.netPay,160000);
  const audit = await payroll.listPayrollCalculations(partnerId);
  assert.equal(audit.length,1); assert.equal(audit[0].data.calculation.attendanceDays,.5);
  await assert.rejects(lock.withRecordLock('rollback-payroll',partnerId,async()=>{await payroll.createAttendancePayroll(partnerId,{...values,basicPay:46000});throw Error('rollback');}),/rollback/);
  assert.equal((await prisma.payslip.findUnique({where:{id:slip.id}})).netPay,160000);
  assert.equal((await payroll.listPayrollCalculations(partnerId)).length,1);
  const correction={expected:JSON.stringify({checkInAt:shift.checkInAt.toISOString(),checkOutAt:shift.checkOutAt.toISOString(),status:shift.status}),checkInAt:'2020-01-02T09:00',checkOutAt:'2020-01-02T17:00',status:'Present',reason:'Owner correction'};
  let signal, release;
  const held=new Promise(resolve=>signal=resolve), gate=new Promise(resolve=>release=resolve);
  const correcting=lock.withRecordLock('hrms-attendance',`${partnerId}:${employee.id}`,async()=>{await hrms.correctAttendance(partnerId,shift.id,correction);signal();await gate;});
  await held;
  const finalizing=hrms.setPayslipStatus(partnerId,slip.id,'Finalized');
  const rejected=assert.rejects(finalizing,/Attendance changed/);
  release(); await correcting; await rejected;
  await payroll.createAttendancePayroll(partnerId,values);
  await hrms.upsertPayslip(partnerId,{employeeId:employee.id,month:1,year:2020,basicPayRupees:23000,allowancesRupees:200,deductionsRupees:0});
  await assert.rejects(hrms.setPayslipStatus(partnerId,slip.id,'Finalized'),/manually changed/);
  await payroll.createAttendancePayroll(partnerId,values);
  const leave=await prisma.leaveRequest.create({data:{employeeId:employee.id,leaveType:'Paid',startDate:new Date('2020-01-03'),endDate:new Date('2020-01-03')}});
  assert.equal((await hrms.decideLeaveRequest(partnerId,leave.id,'Approved','Owner')).ok,true);
  await assert.rejects(hrms.setPayslipStatus(partnerId,slip.id,'Finalized'),/Approved leave changed/);
  await payroll.createAttendancePayroll(partnerId,values);
  await hrms.setPayslipStatus(partnerId,slip.id,'Finalized');
  await assert.rejects(payroll.createAttendancePayroll(partnerId,values),/cannot be overwritten/);
  await assert.rejects(hrms.correctAttendance(partnerId,shift.id,{...correction,expected:JSON.stringify({checkInAt:shift.checkInAt.toISOString(),checkOutAt:shift.checkOutAt.toISOString(),status:'Present'}),status:'HalfDay'}),/finalized/);
  const lateLeave=await prisma.leaveRequest.create({data:{employeeId:employee.id,leaveType:'Paid',startDate:new Date('2020-01-06'),endDate:new Date('2020-01-06')}});
  assert.match((await hrms.decideLeaveRequest(partnerId,lateLeave.id,'Approved','Owner')).error,/finalized/);
});
test.after(async()=>{
  await prisma.businessRecord.deleteMany({where:{partnerId}});
  await prisma.payslip.deleteMany({where:{employee:{partnerId}}});
  await prisma.leaveRequest.deleteMany({where:{employee:{partnerId}}});
  await prisma.leaveBalance.deleteMany({where:{employee:{partnerId}}});
  await prisma.attendanceCheckIn.deleteMany({where:{employee:{partnerId}}});
  await prisma.employee.deleteMany({where:{partnerId}});
  await base.$disconnect();
});
